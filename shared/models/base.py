"""Declarative base shared by every ORM model in the project.

A single Base means bot / backend / workers all reference the exact same
table metadata — there is only one schema definition, not one per process.

The naming convention below is what makes Alembic's autogenerate produce
stable, predictable constraint/index names instead of driver-assigned ones
(important once we start writing manual migrations on top of autogenerated
ones — without this, upgrade/downgrade pairs can silently drift).
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import DateTime, MetaData, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Base class for all ORM models."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class TimestampMixin:
    """Adds server-managed created_at / updated_at columns to a model.

    Timezone-aware (`TIMESTAMP WITH TIME ZONE`) on purpose — the whole
    pipeline reasons about freshness/scheduling across UTC and
    Asia/Tashkent, and naive timestamps are a classic source of
    off-by-some-hours bugs once that mixing starts.
    """

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )
